"""Build Items.lua (item ID -> English name) from QuestieDB's Forever TOC.

QuestieDB keeps its baked rows as TOC metadata: "## X-Item-<id>-S: <base64 CBOR map>", field 1 = name.
Optional second source: the Forever client's ItemSparse table as CSV
(https://wago.tools/db2/ItemSparse/csv?branch=wowf); it adds items QuestieDB lacks and wins on names.
Run:  uv run --no-project --with cbor2 python tools/gen_items.py [ItemSparse.csv]
"""
import base64
import csv
import re
import sys
from pathlib import Path

import cbor2

TOC = Path(r"C:\Program Files (x86)\World of Warcraft\_forever_\Interface\AddOns\QuestieDB\QuestieDB_Forever.toc")
OUT = Path(__file__).resolve().parent.parent / "Items.lua"
LINE = re.compile(rb"^## X-Item-(\d+)-S: (\S+)\s*$")
# unused / test rows of the client table
JUNK = re.compile(r"^(OLD|Deprecated|Unused|zz|Monster - |NPC )|^\[(UNUSED|PH)\]|TEST|Test Gear|[(]Test[)]|(?<![A-Za-z])(DEP|DND)(?![A-Za-z])|DEPRECATED")


def lua_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def main():
    toc = TOC
    sparse = Path(sys.argv[1]) if len(sys.argv) > 1 else None
    version = b"?"
    names = {}
    for raw in toc.read_bytes().splitlines():
        if raw.startswith(b"## Version:"):
            version = raw.split(b":", 1)[1].strip()
        m = LINE.match(raw)
        if not m:
            continue
        row = cbor2.loads(base64.b64decode(m.group(2)))
        name = row.get(1) if isinstance(row, dict) else None
        if isinstance(name, bytes):
            name = name.decode("utf-8", "replace")
        if isinstance(name, str) and name.strip():
            names[int(m.group(1))] = name.strip()
    from_questie = len(names)
    added = 0
    if sparse:
        csv.field_size_limit(10**8)
        with open(sparse, encoding="utf-8") as f:
            for row in csv.DictReader(f):
                name = (row.get("Display_lang") or "").strip()
                if not name or JUNK.search(name):
                    continue
                item_id = int(row["ID"])
                if item_id not in names:
                    added += 1
                names[item_id] = name
    print("QuestieDB %d, added from client table %d" % (from_questie, added))
    lines = [
        "-- GENERATED by tools/gen_items.py from QuestieDB_Forever.toc (QuestieDB %s)%s. Do not edit."
        % (version.decode(), " + Forever ItemSparse (wago.tools)" if sparse else ""),
        "-- Item names: data from QuestieDB (GPLv3) and the game client's item table.",
        "local _, ns = ...",
        "ns.ITEMS = {",
    ]
    lines += ["[%d]=%s," % (i, lua_string(names[i])) for i in sorted(names)]
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("%d items -> %s" % (len(names), OUT))


if __name__ == "__main__":
    main()
